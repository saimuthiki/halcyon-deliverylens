"""Regenerate frontend/src/api/lateOrdersSnapshot.ts (the Late same-day orders page's offline fallback).

Runs app.analytics.late_orders.simulate_late_orders on a throwaway SQLite copy of the dataset for every
(grace_until, hard_stop) pair the page offers (half-hour steps, 08:00 <= grace <= hard stop <= 14:00) and
keeps only the numbers that change with the times. The arrivals per half hour, the method and the
assumptions are the same for every pair and are stored once; the rule table is rebuilt from the times.

Run from the repository root:
    backend/.venv/bin/python frontend/scripts/generate_late_orders_snapshot.py
"""
import json
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "frontend" / "src" / "api" / "lateOrdersSnapshot.ts"

# A throwaway database, so the script never touches a real one.
os.environ["DATABASE_URL"] = f"sqlite:///{Path(tempfile.mkdtemp(prefix='late-orders-snapshot-')) / 'snap.db'}"
os.environ["LLM_PROVIDER"] = "mock"
os.environ.setdefault("DATA_DIR", str(ROOT / "data" / "halcyon-dataset"))
sys.path.insert(0, str(ROOT / "backend"))

from app.analytics import late_orders as lo  # noqa: E402
from app.analytics.store import get_dataset  # noqa: E402
from app.db import get_engine  # noqa: E402
from app.loader import load_all  # noqa: E402

# Numbers per pair as compact tuples, in these orders (see the field lists in the .ts file).
POPULATION = ["grace_orders", "urgent_window_orders", "urgent_window_priority_client_orders", "after_hard_stop_orders",
              "incomplete_address_excluded"]
ADDED = ["orders", "extra_orders_per_warehouse_day", "late_avoided_per_year", "sla_penalties_avoided_usd_per_year",
         "at_risk_late_avoided_per_year"]


def j(x) -> str:
    return json.dumps(x, separators=(",", ":"), ensure_ascii=False)


def main():
    load_all(get_engine())
    ds = get_dataset()
    times = [lo.hhmm(m) for m in range(lo.minutes_of(lo.PICK_LIST_CUTOFF), lo.minutes_of(lo.LATEST_TIME) + 1,
                                       lo.TIME_STEP_MINUTES)]
    pairs = {}
    for g in times:
        for h in times:
            if lo.minutes_of(h) < lo.minutes_of(g):
                continue
            r = lo.simulate_late_orders(ds, g, h)
            ot = r["on_time_rate_after_cutoff_orders"]
            pairs[f"{g}|{h}"] = [
                [r["population"][f] for f in POPULATION],
                [r["grace"][f] for f in ADDED],
                [r["urgent_priority_clients_at_most"][f] for f in ADDED],
                r["urgent_other_clients_with_valid_reason"],
                [ot["with_grace"], ot["with_grace_and_urgent_at_most"]],
            ]
    default = lo.simulate_late_orders(ds)
    pop = default["population"]
    fixed = {k: pop[k] for k in ("after_cutoff_same_day", "days", "warehouses", "on_time_rate_today")}
    arrivals = [{"from": a["from"], "to": a["to"], "orders": a["orders"]} for a in default["arrivals"]]

    OUT.write_text(f"""// GENERATED by frontend/scripts/generate_late_orders_snapshot.py from backend/app/analytics/late_orders.py.
// Do not edit by hand; rerun the script after the data or the simulation changes.

/** Times the page offers, every half hour from the 08:00 pick-list cutoff. */
export const TIMES: string[] = {j(times)};

export const DEFAULTS = {j({"grace_until": lo.DEFAULT_GRACE_UNTIL, "hard_stop": lo.DEFAULT_HARD_STOP})};

/** Population numbers that do not depend on the times. */
export const FIXED = {j(fixed)};

/** Orders received per half hour after 08:00 (the window colour follows the times). */
export const ARRIVALS: {{ from: string; to: string; orders: number }}[] = {j(arrivals)};

/** The order of the numbers in the tuples below. */
export const POPULATION_FIELDS = {j(POPULATION)} as const;
export const ADDED_FIELDS = {j(ADDED)} as const;

/** PAIRS["grace|hard"] = [population, grace, urgent priority clients at most, other clients needing a reason,
 *  [on-time with grace, on-time with grace and urgent at most]]. */
export const PAIRS: Record<string, [number[], number[], number[], number, [number, number]]> = {j(pairs)};

export const METHOD = {j(default["method"])};

export const ASSUMPTIONS: string[] = {j(default["assumptions"])};
""", encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size:,} bytes, {len(pairs)} pairs)")


if __name__ == "__main__":
    main()
